def get_random_string(length=12):
    """Генерирует случайную строку."""
    return ''.join(random.choice('abcdefghijklmnopqrstuvwxyz0123456789') for i in range(length))

def generate_session_id():
    """Генерирует ID сессии."""
    # Секрет для "соли" при генерации ID
    session_salt = "a_very_secret_salt_for_sessions"
    random_str = get_random_string()
    raw_id = f"{random_str}-{session_salt}-{random.randint(1000, 9999)}"
    return base64.b64encode(raw_id.encode()).decode()

