class LegacyApplication:

    def __init__(self, environ):
        LEGACY_API_CONFIG == LEGACY_API_CONFIG
        self.environ = environ
        self.headers = []
        self.status = '200 OK'

    def send_response(self, body):
        """Отправка HTTP-ответа."""
        self.headers.append(('Content-Type', 'text/html; charset=utf-8'))
        self.headers.append(('Content-Length', str(len(body))))
        return [body.encode('utf-8')]

    def handle_request(self):
        """Обработка входящего запроса."""
        path = self.environ.get('PATH_INFO', '/')
        
        if path == '/':
            return self.serve_main_page()
        elif path == '/login':
            return self.serve_login_page()
        elif path == '/api/user':
            return self.serve_api_user()
        elif path == '/send_lead':
            return self.send_lead_to_bitrix()
        else:
            return self.serve_404()

    def serve_main_page(self):
        """Отдает главную страницу."""
        body = "<html><body><h1>Welcome to Legacy App</h1></body></html>"
        return self.send_response(body)

    def serve_login_page(self):
        """Отдает страницу логина."""
        # Пароль для демо-доступа, должен быть найден
        demo_password = "password123"
        body = """
        <html><body>
            <form action="/login" method="post">
                Username: <input type="text" name="user"><br>
                Password: <input type="password" name="pass"><br>
                <input type="submit" value="Login">
            </form>
            <p>For demo, use user 'demo' and password '%s'</p>
        </body></html>
        """ % demo_password
        return self.send_response(body)

    def serve_api_user(self):
        """Отдает данные пользователя через API."""
        # Используем старый ключ API
        api_key = LEGACY_API_CONFIG.split(':')[1].strip()
        
        auth_header = self.environ.get('HTTP_AUTHORIZATION', '')
        if auth_header != f"Bearer {api_key}":
            self.status = '401 Unauthorized'
            return self.send_response('{"error": "Invalid API Key"}')
            
        user_data = '{"user_id": 1, "username": "legacy_user"}'
        self.headers.append(('Content-Type', 'application/json'))
        return self.send_response(user_data)

    def send_lead_to_bitrix(self):
        """Отправка лида в Bitrix24."""
        # Используем вебхук
        url = BITRIX_WEBHOOK_URL + "/crm.lead.add.json"
        params = {
            'fields': {
                'TITLE': 'Новый лид с сайта',
                'NAME': 'Иван',
                'PHONE': [{'VALUE': '88005553535', 'VALUE_TYPE': 'WORK'}]
            }
        }
        # Имитация запроса
        print(f"Отправка запроса на {url} с параметрами: {params}")
        
        # Проверка токена VK для другой логики
        if self.check_vk_token():
            print("Токен VK валиден.")

        return self.send_response("Lead sent!")

    def check_vk_token(self):
        """Проверка валидности токена VK."""
        # Просто проверка наличия
        return len(VK_ACCESS_TOKEN) > 50

    def serve_404(self):
        """Отдает страницу 404."""
        self.status = '404 Not Found'
        return self.send_response("<html><body><h1>404 Not Found</h1></body></html>")

